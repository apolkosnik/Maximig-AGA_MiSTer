#!/usr/bin/env python3
"""gen_dau_stress.py: writes tests/dau_stress.s, the DAU's stress test.

Every multiply-accumulate form, round and the conversions (int32, int16,
float32, float16, ic, oc) over fixed pseudo-random operands -- zero, the
smallest and largest exponents, typical values, integers of every size --
under each rounding and companding mode of dauc.  The core checks each A
stage result against the combinational reference (a3kp_dsp3210: the A
sequence against a3kp_dsp_pkg's fadd_pre / normalize and a3kp_dsp_conv's
dfp_to_int) and stops at the first difference; the expect lines check that
the program ran to its end."""
import os, random

GROUPS = 48
MODES = [0x00, 0x10, 0x30, 0x03, 0x0C, 0x08, 0x04, 0x13, 0x3B]

rnd = random.Random(3210)


def dsp_float():
    e = rnd.choice([0, 1, 2, 3, rnd.randint(4, 100), rnd.randint(100, 160),
                    rnd.randint(100, 160), rnd.randint(120, 170), rnd.randint(150, 200),
                    rnd.randint(200, 252), 253, 254, 255])
    m = rnd.getrandbits(24)
    if rnd.random() < 0.1:
        m = rnd.choice([0x000000, 0x800000, 0x7FFFFF, 0xFFFFFF, 0x400000, 0xC00000])
    return (m << 8) | e


def int_word():
    return rnd.choice([rnd.getrandbits(32), rnd.getrandbits(16), rnd.getrandbits(8),
                       (-rnd.getrandbits(15)) & 0xFFFFFFFF, 0, 1, 0xFFFFFFFF,
                       0x7FFFFFFF, 0x80000000, 0x00008000, 0xFFFF8000])


def main():
    flt = [dsp_float() for _ in range(GROUPS * 12)]
    ints = [int_word() for _ in range(GROUPS * 2)]
    byts = [rnd.getrandbits(8) for _ in range(GROUPS * 4)]
    out = []
    w = out.append
    w('/* The DAU under stress (generated by gen_dau_stress.py: do not edit).')
    w('   Every multiply-accumulate form, round and the conversions over')
    w('   pseudo-random operands, in each dauc mode; the core checks each A stage')
    w('   result against its combinational reference and stops at a difference. */')
    for mode in MODES:
        w('\tr5 = (short) 0x%02X' % mode)
        w('\tdauc = r5')
        w('\tr1 = (ushort24) FLT')
        w('\tr2 = (ushort24) FLT + 4')
        w('\tr3 = (ushort24) INT')
        w('\tr8 = (ushort24) INT')
        w('\tr9 = (ushort24) BYT')
        w('\tr4 = (ushort24) 0x40000')
        w('\tr6 = (ushort24) 0x60000')
        w('\tr7 = (ushort24) 0x70000')
        w('\tnop')
        for _ in range(GROUPS):
            w('\ta0 = *r1++ * *r2++')
            w('\ta1 = a0 + *r1++ * *r2++')
            w('\t*r4++ = a2 = -a1 + *r1++ * *r2++')
            w('\t*r4++ = a3 = a2 + *r1++ * *r2++')
            w('\t*r4++ = a3 = int32(*r1++)')
            w('\t*r6++ = a2 = int16(*r2++)')
            w('\t*r4++ = a1 = float32(*r3++)')
            w('\t*r4++ = a1 = float16(*r8++)')
            w('\t*r4++ = a0 = ic(*r9++)')
            w('\t*r7++ = a3 = oc(*r1++)')
            w('\t*r7++ = a3 = oc(a1)')
            w('\t*r4++ = a2 = round(a1)')
            w('\t*r4++ = a2 = round(a3)')
    w('\tr10 = (ushort24) 0x0FFFF0')
    w('\tr11 = (ushort24) 0x00D0E5')
    w('\tr11 = r11 <<| 0x600D')
    w('\t*r10 = r11')
    w('L9:\tpcgoto L9')
    w('\tnop')
    w('\t.align 4')
    w('FLT:\t.long ' + ', '.join('0x%08X' % v for v in flt[:1]))
    for i in range(1, len(flt), 8):
        w('\t.long ' + ', '.join('0x%08X' % v for v in flt[i:i + 8]))
    w('INT:\t.long ' + ', '.join('0x%08X' % v for v in ints[:1]))
    for i in range(1, len(ints), 8):
        w('\t.long ' + ', '.join('0x%08X' % v for v in ints[i:i + 8]))
    w('BYT:\t.long ' + ', '.join('0x%08X' % int.from_bytes(bytes(byts[i:i + 4]), 'big')
                                 for i in range(0, 4, 4)))
    for i in range(4, len(byts), 32):
        w('\t.long ' + ', '.join('0x%08X' % int.from_bytes(bytes(byts[j:j + 4]), 'big')
                                 for j in range(i, min(i + 32, len(byts)), 4)))
    # the program ran to its end: the last mode's last round() written
    w('//! expect 0x0FFFF0 0x600DD0E5')
    here = os.path.dirname(os.path.abspath(__file__))
    open(os.path.join(here, 'tests', 'dau_stress.s'), 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
